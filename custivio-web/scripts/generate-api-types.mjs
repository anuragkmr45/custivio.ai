import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const outputPath = path.join(repoRoot, "src/lib/api/generated/openapi.ts");

const METHODS = ["get", "post", "put", "patch", "delete"];

async function main() {
  const document = await loadOpenApiDocument();
  const paths = document.paths;

  if (!paths || typeof paths !== "object" || Array.isArray(paths)) {
    throw new Error("OpenAPI document does not contain a valid paths object.");
  }

  const operations = Object.entries(paths)
    .flatMap(([openApiPath, methods]) => {
      if (!methods || typeof methods !== "object" || Array.isArray(methods)) return [];
      return Object.entries(methods)
        .filter(([method]) => METHODS.includes(method))
        .map(([method, operation]) => toOperation(openApiPath, method, operation));
    })
    .sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));

  if (operations.length === 0) {
    throw new Error("OpenAPI document does not expose any HTTP operations.");
  }

  const pathList = [...new Set(operations.map((operation) => operation.path))].sort();
  const tagList = [...new Set(operations.flatMap((operation) => operation.tags))].sort();

  const sourceLabel = process.env.API_OPENAPI_FILE
    ? path.relative(repoRoot, path.resolve(process.env.API_OPENAPI_FILE))
    : (process.env.API_OPENAPI_URL ?? defaultOpenApiUrl());

  const content = `// Generated by scripts/generate-api-types.mjs from ${sourceLabel}.
// Do not edit by hand.

export type OpenApiHttpMethod = ${METHODS.map((method) => JSON.stringify(method)).join(" | ")};

export const OPENAPI_PATHS = ${JSON.stringify(pathList, null, 2)} as const;

export type OpenApiPath = (typeof OPENAPI_PATHS)[number];

export const OPENAPI_TAGS = ${JSON.stringify(tagList, null, 2)} as const;

export type OpenApiTag = (typeof OPENAPI_TAGS)[number];

export const OPENAPI_OPERATIONS = ${JSON.stringify(operations, null, 2)} as const;

export type OpenApiOperation = (typeof OPENAPI_OPERATIONS)[number];
export type OpenApiOperationId = OpenApiOperation["operationId"];

export type OpenApiDocument = {
  openapi: string;
  info: {
    title: string;
    version: string;
  };
  paths: Record<OpenApiPath, unknown>;
};
`;

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, "utf8");
  console.log(
    `Generated ${path.relative(repoRoot, outputPath)} with ${operations.length} operations.`,
  );
}

async function loadOpenApiDocument() {
  const file = process.env.API_OPENAPI_FILE;
  if (file) {
    return JSON.parse(await readFile(path.resolve(file), "utf8"));
  }

  const url = process.env.API_OPENAPI_URL ?? defaultOpenApiUrl();
  const response = await fetch(url, { headers: { accept: "application/json" } });
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: HTTP ${response.status}`);
  }
  return response.json();
}

function defaultOpenApiUrl() {
  const baseUrl = process.env.VITE_API_BASE_URL ?? "http://localhost:3002";
  return `${baseUrl.replace(/\/$/, "")}/api/openapi.json`;
}

function toOperation(openApiPath, method, rawOperation) {
  const operation = rawOperation && typeof rawOperation === "object" ? rawOperation : {};
  const tags = Array.isArray(operation.tags)
    ? operation.tags.filter((tag) => typeof tag === "string").sort()
    : [];
  const responses =
    operation.responses && typeof operation.responses === "object"
      ? Object.keys(operation.responses).sort()
      : [];

  return {
    method,
    path: openApiPath,
    operationId:
      typeof operation.operationId === "string"
        ? operation.operationId
        : `${method.toUpperCase()} ${openApiPath}`,
    tags,
    summary: typeof operation.summary === "string" ? operation.summary : "",
    hasRequestBody: Boolean(operation.requestBody),
    responses,
  };
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
